import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('public pages fit a mobile viewport and update search metadata', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  for (const route of ['/', '/services', '/about', '/contact']) {
    const response = await page.goto(route)
    expect(response?.ok()).toBe(true)
    await expect(page.getByRole('main')).toBeVisible()
    const logo = page.getByRole('link', { name: 'NexRoad home' }).first()
    await expect(logo).toHaveAttribute('href', '/')
    const icon = logo.locator('img')
    await expect(icon).toHaveAttribute('src', '/logo/nexroad-road-pin.webp')
    await expect.poll(() => icon.evaluate(image => image.naturalWidth)).toBe(256)
    await expect(page.locator('link[rel="icon"]')).toHaveAttribute('href', '/nexroad-favicon.png')
    await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href', new RegExp(route === '/' ? '/$' : route + '$'))
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  }
  const favicon = await page.goto('/nexroad-favicon.png')
  expect(favicon?.ok()).toBe(true)
  expect(favicon?.headers()['content-type']).toMatch(/^image\/png/)
  await page.goto('/admin/dashboard')
  await expect(page).toHaveURL(/\/login(?:\?|$)/)
  await expect(page.locator('meta[name=robots]')).toHaveAttribute('content', /noindex/)
})

test('login screen passes automated accessibility checks', async ({ page }) => {
  await page.goto('/login')
  await expect(page.getByRole('button', { name: /sign in|log in/i }).first()).toBeVisible()
  const { violations } = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(violations.map(({ id, nodes }) => ({ id, elements: nodes.map(({ target }) => target) }))).toEqual([])
})

test('sign-in copies entered credentials and keeps the password masked by default', async ({ context, page }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/login')
  const email = page.locator('input[name=email]')
  const password = page.locator('input[name=password]')
  await expect(page.getByText(/Try NexRoad Demo|Sign in with a demo account/)).toHaveCount(0)
  await page.getByRole('button', { name: 'Copy email address' }).click()
  await expect(page.getByRole('status')).toHaveText('Enter your email address first.')
  await email.fill('copy-fixture@example.com')
  await password.fill('copy-fixture-password')
  await expect(password).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Copy email address' }).click()
  await expect(page.getByRole('status')).toHaveText('Email address copied.')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('copy-fixture@example.com')
  await page.getByRole('button', { name: 'Show password' }).click()
  await expect(password).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Copy password' }).click()
  await expect(page.getByRole('status')).toHaveText('Password copied.')
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('copy-fixture-password')
  await page.getByRole('button', { name: 'Hide password' }).click()
  await expect(password).toHaveAttribute('type', 'password')
})
